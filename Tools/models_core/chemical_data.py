def calc_shomate(species: str, temperature: float) -> Optional[dict]:
    """计算指定物种在给定温度下的 Shomate 热力学性质

    Cp = A + B*t + C*t^2 + D*t^3 + E/t^2   (J/mol·K),  t = T/1000
    H° - H°298 = A*t + B*t²/2 + C*t³/3 + D*t⁴/4 - E/t + F - H  (kJ/mol)
    S° = A·ln(t) + B*t + C*t²/2 + D*t³/3 - E/(2*t²) + G  (J/mol·K)
    """
    params = SHOMATE_PARAMS.get(species)
    if not params:
        return None
    if temperature < params["T_min"] or temperature > params["T_max"]:
        return None

    t = temperature / 1000.0
    A, B, C, D, E = params["A"], params["B"], params["C"], params["D"], params["E"]
    F, G, H = params["F"], params["G"], params["H"]

    Cp = A + B*t + C*t**2 + D*t**3 + E/t**2
    H_minus_H298 = A*t + B*t**2/2 + C*t**3/3 + D*t**4/4 - E/t + F - H
    import math
    ln_t = math.log(t) if t > 0 else 0
    S = A * ln_t + B * t + C * t**2 / 2 + D * t**3 / 3 - E / (2 * t**2) + G

    return {
        "species": species,
        "temperature": temperature,
        "Cp": round(Cp, 6),
        "Cp_unit": "J/(mol·K)",
        "H_minus_H298": round(H_minus_H298, 4),
        "H_unit": "kJ/mol",
        "S": round(S, 4),
        "S_unit": "J/(mol·K)",
        "T_min": params["T_min"],
        "T_max": params["T_max"],
        "in_range": params["T_min"] <= temperature <= params["T_max"],
    }
