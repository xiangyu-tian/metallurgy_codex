def find_reaction(reaction_str: str) -> Optional[ThermoEntry]:
    """根据反应式查找热化学数据"""
    for entry in THERMOCHEMICAL_DB:
        if entry["reaction"] == reaction_str:
            return entry
    return None


def list_reactions() -> List[str]:
    """列出所有支持的反应式"""
    return [entry["reaction"] for entry in THERMOCHEMICAL_DB]


